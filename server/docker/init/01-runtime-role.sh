#!/bin/sh
set -eu
read_secret() { test -r "$1" || { echo "Required secret is missing: $1" >&2; exit 1; }; tr -d '\r\n' < "$1"; }
RUNTIME_PASSWORD="$(read_secret "${ARM_RUNTIME_PASSWORD_FILE:?}")"
WORKER_PASSWORD="$(read_secret "${ARM_WORKER_PASSWORD_FILE:?}")"
MIGRATOR_PASSWORD="$(read_secret "${ARM_MIGRATOR_PASSWORD_FILE:?}")"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  -v runtime_password="$RUNTIME_PASSWORD" \
  -v worker_password="$WORKER_PASSWORD" \
  -v migrator_password="$MIGRATOR_PASSWORD" <<'SQL'
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='arm_runtime') THEN
    CREATE ROLE arm_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='arm_worker') THEN
    CREATE ROLE arm_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='arm_migrator') THEN
    CREATE ROLE arm_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
END
$$;
ALTER ROLE arm_runtime WITH LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
ALTER ROLE arm_worker WITH LOGIN PASSWORD :'worker_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
ALTER ROLE arm_migrator WITH LOGIN PASSWORD :'migrator_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
GRANT CONNECT ON DATABASE arm TO arm_runtime,arm_worker,arm_migrator;
ALTER SCHEMA public OWNER TO arm_migrator;
GRANT USAGE,CREATE ON SCHEMA public TO arm_migrator;
GRANT USAGE ON SCHEMA public TO arm_runtime,arm_worker;
SQL
