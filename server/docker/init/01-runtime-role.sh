#!/bin/sh
set -eu
: "\${ARM_RUNTIME_PASSWORD:?ARM_RUNTIME_PASSWORD is required}"
: "\${ARM_WORKER_PASSWORD:?ARM_WORKER_PASSWORD is required}"
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v runtime_password="$ARM_RUNTIME_PASSWORD" -v worker_password="$ARM_WORKER_PASSWORD" <<'SQL'
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'arm_runtime') THEN
    CREATE ROLE arm_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'arm_worker') THEN
    CREATE ROLE arm_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
END
$$;
SELECT format('ALTER ROLE arm_runtime WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'runtime_password') \gexec
SELECT format('ALTER ROLE arm_worker WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS', :'worker_password') \gexec
GRANT CONNECT ON DATABASE arm TO arm_runtime, arm_worker;
GRANT USAGE ON SCHEMA public TO arm_runtime, arm_worker;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO arm_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO arm_runtime;
SQL
